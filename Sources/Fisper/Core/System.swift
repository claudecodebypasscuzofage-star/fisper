// MARK: - Inserting text into the focused app

enum Paster {
    enum Result { case pasted, copiedOnly }

    /// Puts `text` into whatever field has focus, by pasting. The user's clipboard is restored afterwards.
    @MainActor
    static func insert(_ text: String, restoreClipboard: Bool) -> Result {
        let pb = NSPasteboard.general
        let saved = restoreClipboard ? snapshot(pb) : nil

        pb.clearContents()
        pb.setString(text, forType: .string)
        // hint to clipboard managers that this entry is transient
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let ourChange = pb.changeCount

        guard AXIsProcessTrusted() else { return .copiedOnly }
        postCommandV()

        let hasFocusedElement = FocusInspector.focusedElement() != nil
        if let saved, hasFocusedElement {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
                // only restore if nothing else touched the clipboard in the meantime
                guard pb.changeCount == ourChange else { return }
                pb.clearContents()
                if !saved.isEmpty { pb.writeObjects(saved) }
            }
        }
        return .pasted
    }

    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).compactMap { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy.types.isEmpty ? nil : copy
        }
    }

    static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        src?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents], state: .eventSuppressionStateSuppressionInterval)
        let vKey = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        for e in [down, up] {
            e?.flags = .maskCommand
            e?.setIntegerValueField(.eventSourceUserData, value: HotkeyManager.syntheticMarker)
        }
        down?.post(tap: .cghidEventTap)
        usleep(8_000)
        up?.post(tap: .cghidEventTap)
    }
}

// MARK: - Reading the focused text field (for smart spacing / capitalization)

enum FocusInspector {
    static func focusedElement() -> AXUIElement? {
        let sys = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(sys, 0.12)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(sys, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let f = focused, CFGetTypeID(f) == AXUIElementGetTypeID() else { return nil }
        return (f as! AXUIElement)
    }

    /// Up to 80 characters immediately before the insertion point, or nil if unknown.
    static func textBeforeCursor() -> String? {
        guard AXIsProcessTrusted(), let el = focusedElement() else { return nil }
        AXUIElementSetMessagingTimeout(el, 0.12)
        var rangeRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
              let rr = rangeRef, CFGetTypeID(rr) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(rr as! AXValue, .cfRange, &range) else { return nil }
        if range.location <= 0 { return "" }
        let start = max(0, range.location - 80)
        var r = CFRange(location: start, length: range.location - start)
        if let axr = AXValueCreate(.cfRange, &r) {
            var strRef: CFTypeRef?
            if AXUIElementCopyParameterizedAttributeValue(el, kAXStringForRangeParameterizedAttribute as CFString, axr, &strRef) == .success,
               let s = strRef as? String { return s }
        }
        var valRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(el, kAXValueAttribute as CFString, &valRef) == .success, let v = valRef as? String {
            let ns = v as NSString
            if range.location <= ns.length { return ns.substring(with: NSRange(location: start, length: range.location - start)) }
        }
        return nil
    }

    /// Electron / Chromium apps only expose their accessibility tree when asked.
    static func enableAccessibility(for app: NSRunningApplication?) {
        guard let app, AXIsProcessTrusted() else { return }
        let el = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetMessagingTimeout(el, 0.1)
        AXUIElementSetAttributeValue(el, "AXManualAccessibility" as CFString, kCFBooleanTrue)
    }
}

// MARK: - Permissions

enum Permissions {
    static var microphone: AVAuthorizationStatus { AVCaptureDevice.authorizationStatus(for: .audio) }
    static var accessibility: Bool { AXIsProcessTrusted() }

    static func requestMicrophone(_ done: @escaping @Sendable (Bool) -> Void) {
        AVCaptureDevice.requestAccess(for: .audio) { ok in DispatchQueue.main.async { done(ok) } }
    }

    static func promptAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    static func openAccessibilitySettings() {
        open("x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")
    }
    static func openMicrophoneSettings() {
        open("x-apple.systempreferences:com.apple.preference.security?Privacy_Microphone")
    }
    static func openKeyboardSettings() {
        open("x-apple.systempreferences:com.apple.Keyboard-Settings.extension")
    }
    static func openAppleIntelligenceSettings() {
        open("x-apple.systempreferences:com.apple.Siri-Settings.extension")
    }
    private static func open(_ s: String) { if let u = URL(string: s) { NSWorkspace.shared.open(u) } }

    /// What the 🌐/fn key does when pressed alone (0 = nothing, 1 = input source, 2 = emoji, 3 = dictation).
    static var globeKeyUsage: Int {
        UserDefaults(suiteName: "com.apple.HIToolbox")?.object(forKey: "AppleFnUsageType") as? Int ?? 2
    }
}

// MARK: - Launch at login

enum LoginItem {
    static var isEnabled: Bool { SMAppService.mainApp.status == .enabled }
    static func set(_ on: Bool) {
        do {
            if on { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
        } catch {
            Log.info("login item: \(error.localizedDescription)")
        }
    }
}

// MARK: - Sounds (synthesized, soft)

@MainActor
enum Sounds {
    private static var players: [String: AVAudioPlayer] = [:]

    static func play(_ name: String) {
        guard Preferences.shared.playSounds else { return }
        if players[name] == nil {
            let data: Data
            switch name {
            case "start": data = tone(freqs: [740, 1110], duration: 0.09, volume: 0.22)
            case "stop": data = tone(freqs: [1110, 740], duration: 0.09, volume: 0.2)
            case "cancel": data = tone(freqs: [520, 390], duration: 0.11, volume: 0.18)
            default: data = tone(freqs: [880], duration: 0.08, volume: 0.15)
            }
            players[name] = try? AVAudioPlayer(data: data)
            players[name]?.prepareToPlay()
        }
        players[name]?.currentTime = 0
        players[name]?.play()
    }

    /// A short two-note chime with a smooth envelope, as 16-bit WAV.
    private static func tone(freqs: [Double], duration: Double, volume: Float) -> Data {
        let sr = 44_100.0
        var samples: [Float] = []
        for (idx, f) in freqs.enumerated() {
            let n = Int(duration * sr)
            for i in 0..<n {
                let t = Double(i) / sr
                let env = sin(Double.pi * Double(i) / Double(n))           // smooth in/out
                let decay = exp(-t * 18)
                let v = sin(2 * Double.pi * f * t) * 0.8 + sin(4 * Double.pi * f * t) * 0.12
                samples.append(Float(v * env * (0.5 + 0.5 * decay)) * volume)
            }
            if idx < freqs.count - 1 { samples.append(contentsOf: [Float](repeating: 0, count: Int(0.012 * sr))) }
        }
        return AudioUtil.wavData(samples, sampleRate: Int(sr))
    }
}
